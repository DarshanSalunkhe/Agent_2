print("BUILDING LANGGRAPH WORKFLOW")
print("=" * 70)


rt_workflow = StateGraph(CrewState)


# ------------------------------------------------------------
# Add nodes
# ------------------------------------------------------------

rt_workflow.add_node(
    "task_input",
    task_input_node
)

rt_workflow.add_node(
    "developer",
    real_time_developer
)

rt_workflow.add_node(
    "tester",
    real_time_tester
)

rt_workflow.add_node(
    "manager_decision",
    manager_decision_node
)

rt_workflow.add_node(
    "archiver",
    archiver_node
)


# ============================================================
# 13. START -> TASK INPUT
# ============================================================

rt_workflow.add_edge(
    START,
    "task_input"
)


# ============================================================
# 14. TASK INPUT ROUTING
# ============================================================

def route_from_input(state: CrewState):

    next_step = state.get(
        "next_step"
    )

    print(
        f"\n[Router] Task input -> {next_step}"
    )

    if next_step == "exit":

        return END

    return "developer"


rt_workflow.add_conditional_edges(
    "task_input",
    route_from_input
)


# ============================================================
# 15. DEVELOPER -> TESTER
# ============================================================

rt_workflow.add_edge(
    "developer",
    "tester"
)


# ============================================================
# 16. TESTER -> MANAGER
# ============================================================

rt_workflow.add_edge(
    "tester",
    "manager_decision"
)


# ============================================================
# 17. MANAGER ROUTING
# ============================================================

def route_from_decision(state: CrewState):

    next_step = state.get(
        "next_step"
    )

    print(
        f"\n[Router] Manager -> {next_step}"
    )

    if next_step == "archiver":

        return "archiver"

    return "task_input"


rt_workflow.add_conditional_edges(
    "manager_decision",
    route_from_decision
)


# ============================================================
# 18. ARCHIVER -> END
# ============================================================

rt_workflow.add_edge(
    "archiver",
    END
)


