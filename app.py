# 10. BUILD LANGGRAPH
# ============================================================

workflow = StateGraph(
    CrewState
)


# ------------------------------------------------------------
# Add nodes
# ------------------------------------------------------------

workflow.add_node(
    "developer",
    developer_node
)

workflow.add_node(
    "tester",
    tester_node
)

workflow.add_node(
    "manager",
    manager_node
)


# ------------------------------------------------------------
# Add edges
# ------------------------------------------------------------

workflow.add_edge(
    START,
    "developer"
)

workflow.add_edge(
    "developer",
    "tester"
)

workflow.add_edge(
    "tester",
    "manager"
)

workflow.add_edge(
    "manager",
    END
)


# ------------------------------------------------------------
# Compile
# ------------------------------------------------------------

crew_graph = workflow.compile()


print("\n")
print("=" * 60)
print("LANGGRAPH COMPILED SUCCESSFULLY")
print("=" * 60)


# ============================================================
# 11. API INPUT MODEL
# ============================================================

class AgentInput(BaseModel):

    input: str = Field(
        description="Coding task for the Developer agent"
    )


# ============================================================
# 12. FORMAT INPUT FOR LANGGRAPH
# ============================================================

def format_for_graph(x) -> dict:

    # LangServe normally sends a dictionary.
    # We also support AgentInput directly.

    if isinstance(x, dict):

        user_input = x.get(
            "input",
            ""
        )

    else:

        user_input = x.input


    if not user_input:

        raise ValueError(
            "Input cannot be empty."
        )


    return {
        "task": user_input
    }


# ============================================================
# 13. EXTRACT FINAL GRAPH RESPONSE
# ============================================================

def extract_graph_response(
    graph_output
) -> str:

    if not isinstance(
        graph_output,
        dict
    ):

        return str(
            graph_output
        )


    # --------------------------------------------------------
    # Extract values from final state
    # --------------------------------------------------------

    task = graph_output.get(
        "task",
        ""
    )

    code = graph_output.get(
        "code",
        ""
    )

    test_cases = graph_output.get(
        "test_cases",
        ""
    )

    execution_output = graph_output.get(
        "execution_output",
        ""
    )

    report = graph_output.get(
        "report",
        ""
    )

    decision = graph_output.get(
        "decision",
        ""
    )


    # --------------------------------------------------------
    # Return JSON string
    # --------------------------------------------------------

    result = {

        "task": task,

        "developer": {
            "code": code
        },

        "tester": {
            "test_cases": test_cases,
            "execution_output": execution_output,
            "report": report
        },

        "manager": {
            "decision": decision
        }
    }


    return json.dumps(
        result,
        indent=2
    )


# ============================================================
# 14. CREATE LANGSERVE CHAIN
# ============================================================

formatted_crew_chain = (

    RunnableLambda(
        format_for_graph
    )

    | crew_graph

    | RunnableLambda(
        extract_graph_response
    )

).with_types(
    input_type=AgentInput,
    output_type=str
)


