# 12. RUN AGENTIC WORKFLOW
# ============================================================

@app.post("/run")
def run_task(request: TaskRequest):

    if not request.task.strip():

        raise HTTPException(
            status_code=400,
            detail="Task cannot be empty."
        )

    print("\n" + "=" * 60)
    print("NEW TASK")
    print("=" * 60)

    print(request.task)

    # --------------------------------------------------------
    # Initial LangGraph state
    # --------------------------------------------------------

    initial_state: CrewState = {

        "task": request.task,

        "messages": [
            HumanMessage(
                content=request.task
            )
        ],

        "code": None,

        "report": None,

        "next_step": "developer"
    }

    try:

        # ----------------------------------------------------
        # Run LangGraph
        # ----------------------------------------------------

        result = rt_app.invoke(
            initial_state,
            config={
                "recursion_limit": 20
            }
        )

        # ----------------------------------------------------
        # Return final state
        # ----------------------------------------------------

        return {
            "success": True,
            "task": result.get("task"),
            "code": result.get("code"),
            "report": result.get("report"),
            "next_step": result.get("next_step")
        }

    except Exception as e:

        print(
            "Workflow execution failed:"
        )

        traceback.print_exc()

        raise HTTPException(
            status_code=500,
            detail=str(e)
        )


