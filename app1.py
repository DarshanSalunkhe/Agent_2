# ============================================================

def manager_decision_node(state: CrewState):

    print("\n")
    print("=" * 70)
    print("MANAGER DASHBOARD")
    print("=" * 70)

    # --------------------------------------------------------
    # IMPORTANT:
    # Read report directly from state.
    # --------------------------------------------------------

    report = state.get("report")

    if report:

        print("\nTEST REPORT:")
        print("-" * 70)
        print(report)
        print("-" * 70)

    else:

        print(
            "\nERROR: Manager did not receive Tester report."
        )

    # --------------------------------------------------------
    # Display state confirmation
    # --------------------------------------------------------

    print("\nMANAGER STATE CHECK:")
    print(
        "Code available:",
        bool(state.get("code"))
    )

    print(
        "Report available:",
        bool(state.get("report"))
    )

    print(
        "Messages available:",
        len(state.get("messages", []))
    )

    print("=" * 70)

    # --------------------------------------------------------
    # Manager decision
    # --------------------------------------------------------

    user_input = input(
        "\nCommand "
        "(store / another): "
    ).lower().strip()

    if user_input == "store":

        return {
            "next_step": "archiver"
        }

    else:

        return {
            "next_step": "task_input"
        }


