# ============================================================
# 3. STATE DEFINITION
# ============================================================

class CrewState(TypedDict, total=False):

    # User's coding task
    task: str

    # Code generated by Developer
    code: str

    # Test cases generated by Tester
    test_cases: str

    # Actual code execution result
    execution_output: str

    # Tester report
    report: str

    # Manager decision
    decision: str


# ============================================================
# 4. HELPER FUNCTION
# ============================================================

def extract_text(content) -> str:
    """
    Safely extract text from Gemini response content.
    """

    if content is None:
        return ""

    if isinstance(content, str):
        return content

    if isinstance(content, list):

        result = []

        for item in content:

            if isinstance(item, dict):

                if "text" in item:
                    result.append(
                        str(item["text"])
                    )

            else:

                result.append(
                    str(item)
                )

        return "".join(result)

    return str(content)


# ============================================================
# 5. PYTHON CODE EXECUTION TOOL
# ============================================================

@tool
def run_python_code(code: str) -> str:
    """
    Execute Python code and return stdout or error.
    """

    if not isinstance(code, str):
        code = str(code)

    # Remove Markdown code fences
    clean_code = (
        code
        .replace("```python", "")
        .replace("```Python", "")
        .replace("```", "")
        .strip()
    )

    old_stdout = sys.stdout
    new_stdout = io.StringIO()

    sys.stdout = new_stdout

    try:

        local_scope = {}

        exec(
            clean_code,
            {},
            local_scope
        )

        result = new_stdout.getvalue()

    except Exception:

        result = (
            "Execution Error:\n"
            + traceback.format_exc()
        )

    finally:

        sys.stdout = old_stdout

    if result.strip():

        return result.strip()

    return "Success (no terminal output)"


# ============================================================
# 6. TEST CASE GENERATION TOOL
# ============================================================

@tool
def generate_test_cases(
    task_description: str
) -> str:
    """
    Generate QA test scenarios for a coding task.
    """

    prompt = f"""
You are a Senior QA Engineer.

Generate 3 to 5 specific test scenarios
for the following Python coding task:

{task_description}

Requirements:

1. Include normal cases.
2. Include edge cases.
3. Include invalid input cases when appropriate.
4. Explain what each test checks.
5. Return ONLY a numbered list.
"""

    response = llm.invoke(prompt)

    return extract_text(
        response.content
    )


# ============================================================
# 7. DEVELOPER NODE
# ============================================================

def developer_node(
    state: CrewState
):

    print("\n")
    print("=" * 60)
    print("DEVELOPER NODE")
    print("=" * 60)

    task = state.get("task")

    if not task:

        raise ValueError(
            "Developer did not receive a task."
        )

    print(
        "\nTask received by Developer:"
    )

    print(task)

    # --------------------------------------------------------
    # Developer prompt
    # --------------------------------------------------------

    prompt = f"""
You are a Senior Python Developer.

Solve the following coding task:

{task}

Requirements:

- Write clean Python code.
- Make it executable.
- Handle reasonable edge cases.
- Return ONLY Python source code.
- Do NOT return explanations.
- Do NOT return Markdown.
- Do NOT use ```python.
"""

    print(
        "\nDeveloper calling Gemini..."
    )

    response = llm.invoke(prompt)

    code = extract_text(
        response.content
    )

    # --------------------------------------------------------
    # Clean response
    # --------------------------------------------------------

    code = (
        code
        .replace("```python", "")
        .replace("```Python", "")
        .replace("```", "")
        .strip()
    )

    if not code:

        raise ValueError(
            "Developer generated empty code."
        )

    print(
        "\nDeveloper generated code:"
    )

    print("-" * 60)

    print(code)

    print("-" * 60)

    # --------------------------------------------------------
    # THIS IS THE STATE UPDATE
    # --------------------------------------------------------

    return {
        "code": code
    }


# ============================================================
# 8. TESTER NODE
# ============================================================

def tester_node(
    state: CrewState
):

    print("\n")
    print("=" * 60)
    print("TESTER NODE")
    print("=" * 60)

    # --------------------------------------------------------
    # Read state from Developer
    # --------------------------------------------------------

    task = state.get("task")

    code = state.get("code")

    print(
        "\nTester received code:",
        bool(code)
    )

    if not task:

        raise ValueError(
            "Tester did not receive task."
        )

    if not code:

        raise ValueError(
            "Tester did not receive Developer code."
        )

    # --------------------------------------------------------
    # Generate test cases
    # --------------------------------------------------------

    print(
        "\nGenerating test cases..."
    )

    test_cases = generate_test_cases.invoke(
        task
    )

    test_cases = extract_text(
        test_cases
    )

    # --------------------------------------------------------
    # Execute Developer code
    # --------------------------------------------------------

    print(
        "\nExecuting Developer code..."
    )

    execution_output = run_python_code.invoke(
        {
            "code": code
        }
    )

    # --------------------------------------------------------
    # Create report
    # --------------------------------------------------------

    report = f"""
### EXECUTION OUTPUT

{execution_output}


### TEST SCENARIOS EVALUATED

{test_cases}
"""

    print(
        "\nTester generated report:"
    )

    print("-" * 60)

    print(report)

    print("-" * 60)

    # --------------------------------------------------------
    # STATE UPDATE
    # --------------------------------------------------------

    return {
        "test_cases": test_cases,
        "execution_output": execution_output,
        "report": report
    }


# ============================================================
# 9. MANAGER NODE
# ============================================================

def manager_node(
    state: CrewState
):

    print("\n")
    print("=" * 60)
    print("MANAGER NODE")
    print("=" * 60)

    # --------------------------------------------------------
    # Read Tester state
    # --------------------------------------------------------

    task = state.get("task")

    code = state.get("code")

    test_cases = state.get(
        "test_cases"
    )

    execution_output = state.get(
        "execution_output"
    )

    report = state.get(
        "report"
    )

    if not report:

        raise ValueError(
            "Manager did not receive Tester report."
        )

    print(
        "\nManager received Tester report."
    )

    print("-" * 60)

    print(report)

    print("-" * 60)

    # --------------------------------------------------------
    # Manager prompt
    # --------------------------------------------------------

    manager_prompt = f"""
You are a Senior Engineering Manager.

Review this coding task:

{task}


DEVELOPER CODE:

{code}


TEST CASES:

{test_cases}


EXECUTION OUTPUT:

{execution_output}


TESTER REPORT:

{report}


Decide whether the implementation is acceptable.

Return ONLY one of these:

APPROVED

or

NEEDS_REVISION
"""

    print(
        "\nManager evaluating implementation..."
    )

    response = llm.invoke(
        manager_prompt
    )

    decision = extract_text(
        response.content
    ).strip()

    # --------------------------------------------------------
    # Normalize decision
    # --------------------------------------------------------

    if "APPROVED" in decision.upper():

        decision = "APPROVED"

    else:

        decision = "NEEDS_REVISION"

    print(
        "\nManager decision:",
        decision
    )

    # --------------------------------------------------------
    # STATE UPDATE
    # --------------------------------------------------------

    return {
        "decision": decision
    }


