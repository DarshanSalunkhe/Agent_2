# ============================================================
# 2. STATE DEFINITION
# ============================================================

class CrewState(TypedDict, total=False):

    # Messages are accumulated using add_messages.
    messages: Annotated[List[BaseMessage], add_messages]

    # Current workflow routing decision.
    next_step: Optional[str]

    # Code generated by Developer.
    code: Optional[str]

    # Test report generated by Tester.
    report: Optional[str]


# ============================================================
# 3. HELPER FUNCTION
# ============================================================

def extract_text(content) -> str:
    """
    Safely convert Gemini/LangChain response content
    into a normal string.
    """

    if content is None:
        return ""

    if isinstance(content, str):
        return content

    if isinstance(content, list):

        parts = []

        for item in content:

            if isinstance(item, dict):

                if "text" in item:
                    parts.append(str(item["text"]))

            else:
                parts.append(str(item))

        return "".join(parts)

    return str(content)


# ============================================================
# 4. PYTHON EXECUTION TOOL
# ============================================================

@tool
def run_python_code(code: str) -> str:
    """
    Execute Python code and return standard output
    or the error traceback.
    """

    if not isinstance(code, str):
        code = str(code)

    # Remove markdown code fences if Gemini accidentally returns them.
    clean_code = (
        code
        .replace("```python", "")
        .replace("```", "")
        .strip()
    )

    old_stdout = sys.stdout
    new_stdout = io.StringIO()

    sys.stdout = new_stdout

    try:

        # Separate namespace for execution.
        local_scope = {}

        exec(clean_code, {}, local_scope)

        result = new_stdout.getvalue()

    except Exception:

        result = (
            "Execution Error:\n"
            + traceback.format_exc()
        )

    finally:

        sys.stdout = old_stdout

    result = result.strip()

    if result:
        return result

    return "Success (no terminal output)"


# ============================================================
# 5. TEST CASE GENERATION TOOL
# ============================================================

@tool
def generate_test_cases(task_description: str) -> str:
    """
    Generate specific test scenarios for a coding task.
    """

    prompt = f"""
You are a Senior QA Engineer.

Generate 3 to 5 highly specific test scenarios
for the following Python coding task:

{task_description}

Requirements:

1. Include normal/standard cases.
2. Include edge cases.
3. Include invalid input cases where appropriate.
4. Explain what each test should verify.
5. Return only a numbered list.
"""

    response = llm.invoke(prompt)

    return extract_text(response.content)


# ============================================================
# 6. DEBUG STATE FUNCTION
# ============================================================

def print_state(label: str, state: CrewState):

    print("\n")
    print("=" * 70)
    print(f"STATE DEBUG -> {label}")
    print("=" * 70)

    print("\nNEXT STEP:")
    print(state.get("next_step"))

    print("\nCODE:")
    code = state.get("code")

    if code:
        print(code)
    else:
        print("<NO CODE>")

    print("\nREPORT:")
    report = state.get("report")

    if report:
        print(report)
    else:
        print("<NO REPORT>")

    print("\nMESSAGES:")

    messages = state.get("messages", [])

    if not messages:
        print("<NO MESSAGES>")
    else:

        for i, message in enumerate(messages):

            print(f"\nMessage {i + 1}")
            print(f"Type: {type(message).__name__}")
            print(f"Content: {message.content}")

    print("=" * 70)


# ============================================================
# 7. TASK INPUT NODE
# ============================================================

def task_input_node(state: CrewState):

    print("\n")
    print("=" * 70)
    print("NEW TASK INITIALIZATION")
    print("=" * 70)

    user_task = input(
        "\nEnter the coding task "
        "(or type 'exit' to quit): "
    ).strip()

    # --------------------------------------------------------
    # EXIT
    # --------------------------------------------------------

    if user_task.lower() == "exit":

        print("\nExiting workflow...")

        return {
            "next_step": "exit"
        }

    # --------------------------------------------------------
    # Create user message
    # --------------------------------------------------------

    message = HumanMessage(
        content=user_task
    )

    new_state = {
        "messages": [message],
        "next_step": "developer",

        # Clear old task information.
        "code": None,
        "report": None
    }

    print_state("AFTER TASK INPUT", new_state)

    return new_state


# ============================================================
# 8. DEVELOPER NODE
# ============================================================

def real_time_developer(state: CrewState):

    print("\n")
    print("=" * 70)
    print("DEVELOPER NODE")
    print("=" * 70)

    # --------------------------------------------------------
    # Check messages
    # --------------------------------------------------------

    messages = state.get("messages", [])

    if not messages:

        raise ValueError(
            "Developer received no messages."
        )

    # --------------------------------------------------------
    # Get latest user task
    # --------------------------------------------------------

    task = messages[-1].content

    print("\nDeveloper received task:")
    print(task)

    # --------------------------------------------------------
    # Prompt Gemini
    # --------------------------------------------------------

    dev_prompt = f"""
You are a Senior Python Developer.

Solve the following coding task:

{task}

Requirements:

1. Write clean Python code.
2. Make the program executable.
3. Handle reasonable edge cases.
4. Do not explain the solution.
5. Do not use Markdown.
6. Return ONLY the Python source code.
"""

    print("\nCalling Gemini Developer...")

    response = llm_flash.invoke(dev_prompt)

    # --------------------------------------------------------
    # Extract response
    # --------------------------------------------------------

    code_str = extract_text(response.content)

    # --------------------------------------------------------
    # Clean Markdown fences
    # --------------------------------------------------------

    code_str = (
        code_str
        .replace("```python", "")
        .replace("```Python", "")
        .replace("```", "")
        .strip()
    )

    if not code_str:

        raise ValueError(
            "Developer generated empty code."
        )

    # --------------------------------------------------------
    # Create updated state
    # --------------------------------------------------------

    updated_state = {
        "code": code_str
    }

    print("\nDeveloper generated:")
    print("-" * 70)
    print(code_str)
    print("-" * 70)

    # --------------------------------------------------------
    # IMPORTANT:
    # The returned code becomes part of LangGraph state.
    # --------------------------------------------------------

    print("\nDeveloper -> Tester state update:")

    print("code exists:", bool(code_str))
    print("code length:", len(code_str))

    return updated_state


# ============================================================
# 9. TESTER NODE
# ============================================================

def real_time_tester(state: CrewState):

    print("\n")
    print("=" * 70)
    print("TESTER NODE")
    print("=" * 70)

    # --------------------------------------------------------
    # Check incoming state
    # --------------------------------------------------------

    print("\nTester received state:")

    print("messages:",
          len(state.get("messages", [])))

    print("code exists:",
          bool(state.get("code")))

    print("report exists:",
          bool(state.get("report")))

    # --------------------------------------------------------
    # Get task
    # --------------------------------------------------------

    messages = state.get("messages", [])

    if not messages:

        raise ValueError(
            "Tester received no messages."
        )

    task = messages[-1].content

    # --------------------------------------------------------
    # Get Developer code
    # --------------------------------------------------------

    code = state.get("code")

    if not code:

        raise ValueError(
            "TESTER ERROR: Developer code was not found in state."
        )

    print("\nTester successfully received Developer code.")

    print("-" * 70)
    print(code)
    print("-" * 70)

    # ========================================================
    # Generate test scenarios
    # ========================================================

    print("\nGenerating test scenarios...")

    test_cases = generate_test_cases.invoke(
        task
    )

    cases_str = extract_text(test_cases)

    # ========================================================
    # Execute Developer code
    # ========================================================

    print("\nExecuting Developer code...")

    execution_result = run_python_code.invoke(
        {
            "code": code
        }
    )

    # ========================================================
    # Build report
    # ========================================================

    report = f"""
### EXECUTION OUTPUT

{execution_result}

### TEST SCENARIOS EVALUATED

{cases_str}
"""

    # ========================================================
    # Return report to LangGraph state
    # ========================================================

    updated_state = {
        "report": report
    }

    print("\nTester generated report:")
    print("-" * 70)
    print(report)
    print("-" * 70)

    print("\nTester -> Manager state update:")
    print("report exists:", bool(report))
    print("report length:", len(report))

    return updated_state


